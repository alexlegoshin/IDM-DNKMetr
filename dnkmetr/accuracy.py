"""Погрешность датчика по методике ГОСТ 8.401-80 (приведённая погрешность),
БЕЗ округления результата до стандартного ряда классов точности — это
сознательное решение: ряд (1; 1.5; 2; 2.5; 4; 5; 6)×10^n нужен, чтобы
ОБЪЯВИТЬ класс точности прибора (порог/предел для всей партии/модели), а
здесь считается фактическая погрешность КОНКРЕТНОГО измерения — округление
её в грубую стандартную ступень стёрло бы именно то, что мы хотим увидеть
(см. обсуждение 12.08.2026).

Датчик по входу — датчик НАПРЯЖЕНИЯ, но вход откалиброван так, чтобы через
него шёл ток возбуждения ровно 5 или 10 мА (см. current_loop.setpoint_a в
config.yaml / выбор уставки в UI). Для уставки 10 мА у датчика заявлен
коэффициент преобразования вход:выход 1:2.5 — то есть номинальный выходной
ток при 10 мА возбуждения 25 мА, это и есть нормирующее значение X_N для
приведённой погрешности. Для 5 мА такого заявленного коэффициента нет —
погрешность ЧЕСТНО не считается (см. ACCURACY_RATIOS ниже: для 5 мА записи
просто нет), вместо того чтобы придумывать номинал произвольно.

Δ здесь — это СИСТЕМАТИЧЕСКОЕ отклонение измеренного среднего от номинала
(|measured_mean - nominal|), а не случайный разброс отдельных отсчётов
(std/SEM) — последний считается и показывается отдельно (см. bench.py) как
повторяемость измерения, в приведённую погрешность не подмешивается.
"""

# Уставка возбуждения (А) -> заявленный коэффициент преобразования вход:выход.
# 0.005 (5 мА) намеренно отсутствует - для неё коэффициент не заявлен.
ACCURACY_RATIOS = {
    0.010: 2.5,
}


def compute_gost_accuracy(measured_mean_a, setpoint_a):
    """Приведённая погрешность по методике ГОСТ 8.401-80 (γ = Δ/X_N × 100%,
    БЕЗ округления до стандартного ряда) для данной уставки — ЕСЛИ для неё
    заявлен коэффициент преобразования (см. ACCURACY_RATIOS), иначе словарь
    с explicit note, что не считается.
    """
    ratio = ACCURACY_RATIOS.get(setpoint_a)
    if ratio is None:
        return {
            "computed": False,
            "note": (f"Погрешность не считается для уставки {setpoint_a*1000:.0f} мА "
                    "(коэффициент преобразования для неё не заявлен)."),
        }

    nominal_a = setpoint_a * ratio
    delta_a = abs(measured_mean_a - nominal_a)
    gamma_percent = delta_a / nominal_a * 100.0
    return {
        "computed": True,
        "nominal_a": nominal_a,
        "delta_a": delta_a,
        "gamma_percent": gamma_percent,
    }

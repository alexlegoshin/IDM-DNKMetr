"""Относительная погрешность выходного тока датчика — просто отклонение
измеренного среднего от ОЖИДАЕМОГО значения, в процентах от ожидаемого.

НЕ приведённая погрешность (это отдельное метрологическое понятие ГОСТ
8.401-80 — нормирование через фиксированное X_N для объявления класса
точности прибора/партии, с округлением класса до стандартного ряда) — здесь
просто δ = |measured - expected| / expected × 100%, без всякой возни с
нормирующими значениями и стандартными рядами (сознательно отброшено —
см. обсуждение 12.08.2026, было реализовано как приведённая по ГОСТ, потом
пользователь попросил убрать это целиком в пользу простой относительной).

Датчик по входу — датчик НАПРЯЖЕНИЯ, но вход откалиброван так, чтобы через
него шёл ток возбуждения ровно 5 или 10 мА (см. current_loop.setpoint_a в
config.yaml / выбор уставки в UI). Для уставки 10 мА известно, какой выходной
ток ДОЛЖЕН получиться — 25 мА (коэффициент преобразования вход:выход 1:2.5),
поэтому погрешность считается. Для 5 мА какой выходной ток должен быть —
неизвестно, поэтому погрешность ЧЕСТНО не считается (см. EXPECTED_OUTPUT_A
ниже: для 5 мА записи просто нет), вместо того чтобы придумывать ожидаемое
значение произвольно.

Δ здесь — это СИСТЕМАТИЧЕСКОЕ отклонение измеренного среднего от ожидаемого
значения (|measured_mean - expected|), а не случайный разброс отдельных
отсчётов (std/SEM) — последний считается и показывается отдельно (см.
bench.py) как повторяемость измерения, в относительную погрешность не
подмешивается.
"""

# Уставка возбуждения (А) -> ожидаемый выходной ток датчика (А).
# 0.005 (5 мА) намеренно отсутствует - для неё ожидаемое значение не известно.
EXPECTED_OUTPUT_A = {
    0.010: 0.025,
}


def compute_relative_error(measured_mean_a, setpoint_a):
    """Относительная погрешность (δ = Δ/expected × 100%) для данной уставки —
    ЕСЛИ для неё известен ожидаемый выходной ток (см. EXPECTED_OUTPUT_A),
    иначе словарь с explicit note, что не считается.
    """
    expected_a = EXPECTED_OUTPUT_A.get(setpoint_a)
    if expected_a is None:
        return {
            "computed": False,
            "note": (f"Погрешность не считается для уставки {setpoint_a*1000:.0f} мА "
                    "(ожидаемый выходной ток для неё не известен)."),
        }

    delta_a = abs(measured_mean_a - expected_a)
    relative_error_percent = delta_a / expected_a * 100.0
    return {
        "computed": True,
        "expected_a": expected_a,
        "delta_a": delta_a,
        "relative_error_percent": relative_error_percent,
    }
